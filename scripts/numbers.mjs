#!/usr/bin/env node
// The figures the site shows, as one Markdown sheet read from data/dashboard/*.json.
// Run it after each harvest and compare with the last sheet (git diff NUMBERS.md):
//   npm run numbers
import { readFileSync } from 'node:fs';

const load = (f) => JSON.parse(readFileSync(new URL(`../data/dashboard/${f}`, import.meta.url)));
const ov = load('overview.json'), fields = load('fields.json'), repos = load('repositories.json');
const num = (x) => (x == null ? 'n/a' : x.toLocaleString('en'));
const out = ['# Figures shown on the site', '', 'Generated by `npm run numbers` from `data/dashboard/`.', '',
  `Harvested: DataCite ${ov.harvested.DataCite}, ANID ${ov.harvested.ANID}.`, '',
  '| Figure | Value |', '|---|---|',
  `| Records | ${num(ov.totalRecords)} |`,
  ...Object.entries(ov.bySource).map(([k, v]) => `| Records from ${k} | ${num(v)} |`),
  `| Average completeness | ${ov.avgCompleteness}% |`,
  ...Object.entries(ov.byType).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| Type ${k} | ${num(v)} |`),
  `| Software DOIs in DataCite / pieces of software | ${num(ov.software.dataciteDois)} / ${num(ov.software.dataciteConcepts)} |`,
  '', '| Field | All | DataCite | ANID |', '|---|---|---|---|',
  ...fields.map((f) => `| ${f.id} | ${f.pct}% | ${f.bySource.DataCite}% | ${f.bySource.ANID}% |`),
  '', '| Publisher (top 50) | Records | Chilean |', '|---|---|---|',
  ...repos.map((r) => `| ${r.name} | ${num(r.count)} | ${r.chilean ? 'yes' : ''} |`)];
console.log(out.join('\n'));
